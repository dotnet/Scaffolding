using System.IO;
using System.Threading.Tasks;
using Xunit;

namespace Microsoft.DotNet.Tools.Scaffold.Tests.AspNet.Integration.Syncfusion;

/// <summary>
/// Runnable baseline coverage for the Syncfusion Blazor Toolkit
/// scaffolder. Verifies that the project the scaffolder produces on
/// the default Blazor Web App layout actually builds end-to-end and
/// contains the required configuration:
///
/// <list type="bullet">
///   <item><description>Syncfusion.Blazor.Toolkit package reference</description></item>
///   <item><description>AddSyncfusionBlazorToolkit service registration in Program.cs</description></item>
///   <item><description>using Syncfusion.Blazor.Toolkit; in Program.cs</description></item>
///   <item><description>@using Syncfusion.Blazor.Toolkit in Components/_Imports.razor</description></item>
///   <item><description>No external stylesheet link in App.razor (2.0.0+ ships styles with the assembly)</description></item>
///   <item><description>No sample UI / no extra Razor components generated by the scaffolder</description></item>
/// </list>
///
/// <para>The build step proves the scaffolder did not corrupt the
/// generated project. Expected apps run; the runner builds both
/// the generated app (here) and the matching expected app (in
/// <c>test/dotnet-scaffolding/baselines</c>).</para>
/// </summary>
[Trait("Suite", "ScaffoldIntegration")]
[Trait("Family", "blazor-syncfusion-toolkit")]
public class SyncfusionBlazorToolkitRunnableBaselineTests : SyncfusionBlazorToolkitIntegrationTestsBase
{
    protected override string TargetFramework => "net11.0";
    protected override string TestClassName => nameof(SyncfusionBlazorToolkitRunnableBaselineTests);

    [Fact]
    public async Task Scaffold_DefaultBlazorWebApp_GeneratesBuildableApp()
    {
        WriteBlazorWebAppScaffold();

        var scaffold = await ScaffoldAsync();
        Assert.True(scaffold.ExitCode == 0,
            $"Scaffold failed.\nOutput: {scaffold.Output}\nError: {scaffold.Error}");

        // Build the generated project — proves the scaffolder did not
        // corrupt Program.cs, the imports file, or the project SDK.
        var build = await BuildGeneratedAsync();
        Assert.True(build.ExitCode == 0,
            $"Generated project build failed.\nOutput: {build.Output}\nError: {build.Error}");

        // Required configuration is present in the generated sources.
        string csproj = File.ReadAllText(_testProjectPath);
        Assert.Contains("Syncfusion.Blazor.Toolkit", csproj);

        string programCs = File.ReadAllText(Path.Combine(_testProjectDir, "Program.cs"));
        AssertValidServiceRegistration(programCs);
        Assert.Contains("using Syncfusion.Blazor.Toolkit", programCs);

        string imports = File.ReadAllText(Path.Combine(_testProjectDir, "Components", "_Imports.razor"));
        Assert.Contains("@using Syncfusion.Blazor.Toolkit", imports);

        // Syncfusion.Blazor.Toolkit 2.0.0+ ships styles with the
        // assembly; no App.razor stylesheet link, no wwwroot/index.html
        // stylesheet link, no sample UI files.
        string appRazor = File.ReadAllText(Path.Combine(_testProjectDir, "Components", "App.razor"));
        Assert.DoesNotContain("Syncfusion.Blazor.Toolkit/styles/fluent.min.css", appRazor);

        Assert.False(File.Exists(Path.Combine(_testProjectDir, "Components", "Pages", "SfGrid.razor")),
            "Syncfusion scaffolder is minimal — no sample UI components.");
        Assert.False(File.Exists(Path.Combine(_testProjectDir, "Components", "Pages", "SfButton.razor")),
            "Syncfusion scaffolder is minimal — no sample UI components.");

        // Host / styles: the scaffolder should not have injected a
        // stylesheet link anywhere.
        if (File.Exists(Path.Combine(_testProjectDir, "wwwroot", "index.html")))
        {
            string indexHtml = File.ReadAllText(Path.Combine(_testProjectDir, "wwwroot", "index.html"));
            Assert.DoesNotContain("Syncfusion.Blazor.Toolkit/styles/fluent.min.css", indexHtml);
        }
    }
}